import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { InputError } from './errors.ts';
import type { ResolvedFlavor } from './resolve.ts';
import { compareStrings, relativePosix } from './util.ts';

const CONFIG_NAME = /^(\d\d)-.+\.config\.php$/;

/** The two digit number of a partial config file name, or undefined when the name does not follow the pattern. */
export const configNumber = (file: string): string | undefined => CONFIG_NAME.exec(file)?.[1];

/** Numbers up to this one (00 to 09) are reserved for files the tool generates. */
const RESERVED_UP_TO = 9;

/** The conventional number ranges: bases use 10 to 49, flavors 50 to 89. */
const RANGES = { bases: [10, 49], flavors: [50, 89] } as const;

/** Keys that belong to the deployment, not to a flavor. */
const DEPLOYMENT_KEYS = new Set([
  'dbtype', 'dbname', 'dbhost', 'dbport', 'dbuser', 'dbpassword', 'dbtableprefix', 'dbpersistent', 'dbdriveroptions',
  'db.replica', 'objectstore', 'objectstore_multibucket', 'trusted_domains', 'instanceid', 'passwordsalt', 'secret',
  'mail_sendmailmode', 'datadirectory',
]);
/** Keys Nextcloud writes itself. */
const NEXTCLOUD_KEYS = new Set(['version', 'installed']);
/** Generated by the tool in the reserved number range, which loads first and could otherwise be overridden. */
const GENERATED_KEYS = new Set(['apps_paths', 'ncw.themes', 'enforce_theme']);

function forbiddenReason(key: string): string | undefined {
  if (DEPLOYMENT_KEYS.has(key) || key.startsWith('mail_smtp')) return 'a deployment key';
  if (NEXTCLOUD_KEYS.has(key)) return 'a key Nextcloud writes itself';
  if (GENERATED_KEYS.has(key)) return 'generated by the tool';
  return undefined;
}

/** Evaluates the partial configs in PHP and returns the top-level keys of each one's `$CONFIG`. */
function configKeys(sources: string[]): Record<string, string[]> {
  const code = `
class OC { public static $SERVERROOT = '/srv/nextcloud'; }
function ncw_keys($file) { $CONFIG = []; include $file; return array_keys($CONFIG); }
$out = [];
foreach (array_slice($argv, 1) as $file) { $out[$file] = ncw_keys($file); }
echo json_encode($out);`;
  const php = spawnSync('php', ['-r', code, ...sources], { encoding: 'utf8' });
  if (php.error) throw new InputError('php is required to check the keys of the partial configs, but it could not be run');
  if (php.status !== 0) {
    throw new InputError(`a partial config could not be evaluated by php: ${(php.stderr || php.stdout).trim()}`);
  }
  return JSON.parse(php.stdout) as Record<string, string[]>;
}

/** The names of the environment variables a partial config reads through getenv. */
export function configEnvReferences(source: string): string[] {
  const names = new Set<string>();
  for (const reference of source.matchAll(/\bgetenv\(\s*(['"])([^'"]+)\1\s*\)/g)) names.add(reference[2] as string);
  return [...names];
}

export interface ConfigCheck {
  /** Every environment variable the partial configs refer to, with the file that first does. */
  envReferences: Map<string, string>;
  /** Warnings for the build log. */
  warnings: string[];
}

/**
 * Checks the partial configs of a resolved flavor: names and numbers, forbidden keys (evaluated by running PHP)
 * and environment variable references (a scan for getenv('NAME')). A name needs a two digit number, 00 to 09
 * are reserved, two different names with one number are rejected, and a number outside the convention is a warning.
 */
export function checkConfigs(flavor: ResolvedFlavor, flavorsRoot: string): ConfigCheck {
  const byNumber = new Map<string, string[]>();
  const sources: string[] = [];
  const warnings: string[] = [];
  for (const [file, source] of flavor.configs) {
    const flavorsRelativePath = relativePosix(flavorsRoot, source);
    const owner = flavorsRelativePath.startsWith('bases/') ? 'bases' : 'flavors';
    const match = CONFIG_NAME.exec(file);
    if (!match) throw new InputError(`${flavorsRelativePath}: a partial config must be named NN-<name>.config.php with a two digit number`);
    const number = Number(match[1]);
    if (number <= RESERVED_UP_TO) {
      throw new InputError(`${flavorsRelativePath}: numbers 00 to 09 are reserved for generated files`);
    }
    const [low, high] = RANGES[owner];
    const replacesBaseFile = owner === 'flavors' && flavor.order.some((label) => label.startsWith('bases/') && existsSync(join(flavorsRoot, label, 'config', file)));
    if ((number < low || number > high) && !replacesBaseFile) {
      warnings.push(`warning: config file ${flavorsRelativePath} uses number ${match[1]}, bases use 10-49 and flavors use 50-89`);
    }
    byNumber.set(match[1] as string, [...(byNumber.get(match[1] as string) ?? []), flavorsRelativePath]);
    sources.push(source);
  }
  for (const [number, files] of byNumber) {
    if (files.length > 1) throw new InputError(`two partial configs have number ${number}: ${files.join(' and ')}`);
  }

  const envReferences = new Map<string, string>();
  const keys = sources.length > 0 ? configKeys(sources) : {};
  for (const source of sources) {
    const flavorsRelativePath = relativePosix(flavorsRoot, source);
    for (const key of keys[source] ?? []) {
      const reason = forbiddenReason(key);
      if (reason) throw new InputError(`${flavorsRelativePath}: the key "${key}" is not allowed in a flavor config, it is ${reason}`);
    }
    for (const name of configEnvReferences(readFileSync(source, 'utf8'))) if (!envReferences.has(name)) envReferences.set(name, flavorsRelativePath);
  }
  return { envReferences, warnings };
}

/**
 * Every environment variable referenced must be declared in a manifest (an input error otherwise). Returns
 * warnings for declared variables nothing refers to. `references` maps a variable to where it was found.
 */
export function checkEnvironment(flavor: ResolvedFlavor, references: Map<string, string>): string[] {
  for (const [name, where] of references) {
    if (!flavor.env.has(name)) throw new InputError(`${where}: environment variable ${name} is used but not declared in a manifest`);
  }
  return [...flavor.env.keys()].sort(compareStrings)
    .filter((name) => !references.has(name))
    .map((name) => `warning: environment variable ${name} is declared but not used`);
}
