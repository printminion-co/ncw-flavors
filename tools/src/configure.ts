import { InputError } from './errors.ts';
import type { ResolvedFlavor } from './resolve.ts';
import { compareStrings } from './util.ts';

/** The name of the script at the root of every artifact; the deployment runs it as `bash ncw-configure.sh`. */
export const CONFIGURE_SCRIPT = 'ncw-configure.sh';

const ENV_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;

/** A bash single-quoted string literal. */
const shQuote = (value: string): string => `'${value.replace(/'/g, `'\\''`)}'`;

/** The PHP that fills `${VAR}` placeholders in every string of a decoded JSON document; the value comes from the environment. */
const FILL_PHP = String.raw`function ncw_fill($v) {
  if (is_string($v)) {
    return preg_replace_callback('/\$\{([A-Za-z_][A-Za-z0-9_]*)\}/', function ($m) {
      $value = getenv($m[1]);
      if ($value === false) {
        fwrite(STDERR, 'ncw-configure: the settings use $' . '{' . $m[1] . '} but the environment has no ' . $m[1] . "\n");
        exit(1);
      }
      return $value;
    }, $v);
  }
  if (is_array($v)) return array_map('ncw_fill', $v);
  if (is_object($v)) { foreach ($v as $k => $x) $v->$k = ncw_fill($x); }
  return $v;
}
function ncw_read($file) {
  $d = json_decode((string) file_get_contents($file));
  if ($d === null) { fwrite(STDERR, 'ncw-configure: ' . $file . " is not valid JSON\n"); exit(1); }
  return ncw_fill($d);
}`;

const IMPORT_PHP = String.raw`file_put_contents($argv[2], json_encode(ncw_read($argv[1]), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n");`;

const SPECIAL_PHP = String.raw`$list = ncw_read($argv[1]);
if (!is_array($list)) { fwrite(STDERR, "ncw-configure: app-config-special.json must be a list\n"); exit(1); }
$out = '';
foreach ($list as $e) {
  $out .= $e->app . "\0" . $e->key . "\0" . $e->value . "\0" . ($e->type ?? '') . "\0" . (!empty($e->lazy) ? '1' : '0') . "\0" . (!empty($e->sensitive) ? '1' : '0') . "\0";
}
file_put_contents($argv[2], $out);`;

const ENABLED_PHP = String.raw`$l = json_decode(file_get_contents($argv[1]), true);
exit(is_array($l) && isset($l['enabled'][$argv[2]]) ? 0 : 1);`;

/**
 * The script the deployment runs after every install and every upgrade. It is a pure function of the resolved
 * flavor (its declared environment variables and its `enable_after_install` apps); the settings themselves are read
 * from the `app-config.json` and `app-config-special.json` next to it.
 */
export function renderConfigureScript(flavor: ResolvedFlavor): string {
  const env = [...flavor.env.values()].sort((a, b) => compareStrings(a.name, b.name));
  for (const declaration of env) {
    if (!ENV_NAME.test(declaration.name)) throw new InputError(`the environment variable "${declaration.name}" of flavor ${flavor.name} is not a valid name`);
  }
  const required = env.filter((e) => e.required).map((e) => e.name);
  const optional = env.filter((e) => !e.required);
  const lines = (items: string[]): string => (items.length > 0 ? items.map((i) => `#   ${i}`).join('\n') : '#   (none)');
  const array = (items: string[]): string => `(${items.map(shQuote).join(' ')})`;

  return `#!/usr/bin/env bash
# ncw-configure.sh: the occ work of flavor ${flavor.name}, generated by the flavors tool. Do not edit: \`ncw validate\`
# compares this file with the one generated for the flavor.
#
# WHAT IT DOES, in this order, and stops at the first failure (non-zero exit status):
#   1. imports app-config.json with \`occ config:import\`; \${VAR} placeholders are filled from the environment first;
#   2. sets every entry of app-config-special.json (settings the import cannot set: sensitive, lazy, typed) with
#      \`occ config:app:set --value ... [--type T] [--lazy] [--sensitive]\`, placeholders filled the same way;
#   3. enables the apps the flavor lists in enable_after_install with \`occ app:enable\`, unless \`occ app:list\` shows
#      them enabled already (they are mode available: the installer cannot enable them).
# It prints one line per step and never prints a value.
#
# WHEN TO RUN IT: after \`occ maintenance:install\`, and after \`occ upgrade\` on every upgrade, with the same
# environment as the instance. It is idempotent: running it again changes nothing that is already set.
#
# USAGE: bash ncw-configure.sh      (the zip keeps no unix modes, so it is not executable)
# NEEDS: bash 4.4 or newer and the php of the instance. Nothing else (no jq, no envsubst, no python).
# ENVIRONMENT:
#   OCC   the occ command, default: php occ in the folder of this script (tests replace it)
#   PHP   the php binary for the JSON work, default: php
# Variables of flavor ${flavor.name} (declared in its manifest):
#   required, the script fails early and names every one that is unset or empty:
${lines(required)}
#   optional, with the declared default used when unset:
${lines(optional.map((e) => (e.default === undefined ? `${e.name} (no default: empty)` : `${e.name} (default ${JSON.stringify(e.default)})`)))}
set -euo pipefail

HERE=$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)
PHP=\${PHP:-php}
if [ -n "\${OCC:-}" ]; then read -r -a OCC_CMD <<<"$OCC"; else OCC_CMD=("$PHP" "$HERE/occ"); fi

REQUIRED_VARS=${array(required)}
OPTIONAL_VARS=${array(optional.map((e) => e.name))}
OPTIONAL_DEFAULTS=${array(optional.map((e) => e.default ?? ''))}
ENABLE_APPS=${array(flavor.enableAfterInstall)}

say() { echo "ncw-configure: $*"; }
fail() { echo "ncw-configure: $*" >&2; exit 1; }

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

FILL_PHP=$(cat <<'PHP'
${FILL_PHP}
PHP
)

IMPORT_PHP=$(cat <<'PHP'
${IMPORT_PHP}
PHP
)

SPECIAL_PHP=$(cat <<'PHP'
${SPECIAL_PHP}
PHP
)

ENABLED_PHP=$(cat <<'PHP'
${ENABLED_PHP}
PHP
)

# the declared environment: required variables must be set, optional ones fall back to their default (for the
# placeholders only; the environment of occ is left as it is)
missing=()
for name in "\${REQUIRED_VARS[@]}"; do
  [ -n "\${!name:-}" ] || missing+=("$name")
done
if [ \${#missing[@]} -gt 0 ]; then
  fail "required environment variable(s) not set or empty: $(IFS=,; echo "\${missing[*]}" | sed 's/,/, /g')"
fi
FILL_ENV=()
for i in "\${!OPTIONAL_VARS[@]}"; do
  name=\${OPTIONAL_VARS[$i]}
  if [ -z "\${!name+x}" ]; then FILL_ENV+=("$name=\${OPTIONAL_DEFAULTS[$i]}"); fi
done
fill() { env "\${FILL_ENV[@]}" "$PHP" -r "$FILL_PHP"$'\\n'"$1" "$2" "$3"; }

[ -f "$HERE/app-config.json" ] || fail "$HERE/app-config.json does not exist"
[ -f "$HERE/app-config-special.json" ] || fail "$HERE/app-config-special.json does not exist"

say "importing app-config.json"
fill "$IMPORT_PHP" "$HERE/app-config.json" "$WORK/app-config.json" || fail "could not fill the placeholders of app-config.json"
"\${OCC_CMD[@]}" config:import "$WORK/app-config.json" || fail "occ config:import failed"

fill "$SPECIAL_PHP" "$HERE/app-config-special.json" "$WORK/special.bin" || fail "could not read app-config-special.json"
mapfile -d '' -t SPECIAL < "$WORK/special.bin"
for ((i = 0; i + 5 < \${#SPECIAL[@]}; i += 6)); do
  say "setting \${SPECIAL[i]} \${SPECIAL[i + 1]}"
  args=("\${SPECIAL[i]}" "\${SPECIAL[i + 1]}" "--value=\${SPECIAL[i + 2]}")
  [ -z "\${SPECIAL[i + 3]}" ] || args+=("--type=\${SPECIAL[i + 3]}")
  [ "\${SPECIAL[i + 4]}" != 1 ] || args+=(--lazy)
  [ "\${SPECIAL[i + 5]}" != 1 ] || args+=(--sensitive)
  "\${OCC_CMD[@]}" config:app:set "\${args[@]}" > /dev/null || fail "occ config:app:set failed for \${SPECIAL[i]} \${SPECIAL[i + 1]}"
done

if [ \${#ENABLE_APPS[@]} -gt 0 ]; then
  "\${OCC_CMD[@]}" app:list --output=json > "$WORK/app-list.json" || fail "occ app:list failed"
  for app in "\${ENABLE_APPS[@]}"; do
    if "$PHP" -r "$ENABLED_PHP" "$WORK/app-list.json" "$app"; then
      say "app $app is already enabled"
    else
      say "enabling app $app"
      "\${OCC_CMD[@]}" app:enable "$app" || fail "occ app:enable $app failed"
    fi
  done
fi
`;
}
